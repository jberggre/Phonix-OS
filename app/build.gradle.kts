android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.aistudio.phonix.vpxmkr"
    minSdk = 24
    targetSdk = 36
    versionCode = 6
    versionName = "1.5"

    // The update feed is a build input, never a hardcoded endpoint. A unit built with no feed
    // configured says so; it must not claim it is current when it has not checked anything.
    //   gradle -PphonixUpdateFeed=https://example.org/phonix/update.json assembleDebug
    // or set PHONIX_UPDATE_FEED in the environment.
    val updateFeed = providers.gradleProperty("phonixUpdateFeed")
      .orElse(providers.environmentVariable("PHONIX_UPDATE_FEED"))
      .orElse("")
      .get()
      .replace("\\", "\\\\")
      .replace("\"", "\\\"")
    buildConfigField("String", "UPDATE_FEED_URL", "\"$updateFeed\"")

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  // The debug keystore is the device-owner signing key on the bench unit: this package holds
  // DevicePolicyManager ownership, so the same key must sign every build that updates it.
  // Never regenerate debug.keystore; a different certificate cannot replace an owner.
  // The release config is optional and unused by the documented install path (assembleDebug).
  signingConfigs {
    create("release") {
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD")
      keyAlias = "upload"
      keyPassword = System.getenv("KEY_PASSWORD")
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release")
    }
    debug {
      // Signed with the device-owner key so a debug build can update the provisioned package.
      signingConfig = signingConfigs.getByName("debugConfig")
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  // proot is executed straight out of nativeLibraryDir, so the .so files must be extracted
  // from the APK on install instead of being mapped from inside it.
  packaging {
    jniLibs {
      useLegacyPackaging = true
    }
  }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}



